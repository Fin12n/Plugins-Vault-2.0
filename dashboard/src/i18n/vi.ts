export type I18nDictionary = typeof viRaw;

export const vi: I18nDictionary = new Proxy(viRaw, {
  get(_target, prop: keyof I18nDictionary) {
    const dict = activeLanguage === 'en' ? en : viRaw;
    return dict[prop];
  },
});

/** Formats a byte count for display. */
export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/** Formats VND without decimals, e.g. 20.000 ₫ */
export function formatVnd(amount: number): string {
  const locale = activeLanguage === 'en' ? 'en-US' : 'vi-VN';
  return `${amount.toLocaleString(locale)} ₫`;
}

/** Coins for display. Floors, matching the server: the remainder stays spendable. */
export function toCoins(vnd: number): number {
  return Math.floor(vnd / 1000);
}

