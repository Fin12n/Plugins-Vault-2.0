import { en } from './en.js';

let activeLanguage: 'vi' | 'en' = (() => {
  try {
    const saved = localStorage.getItem('dashboard-lang');
    return saved === 'en' ? 'en' : 'vi';
  } catch {
    return 'vi';
  }
})();

export function setActiveLanguage(lang: 'vi' | 'en') {
  activeLanguage = lang;
}

export function getActiveLanguage(): 'vi' | 'en' {
  return activeLanguage;
}

